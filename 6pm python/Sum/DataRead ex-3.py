#Program for cal Area of Rectangle
L=input("Enter Length:")
B=input("Enter Breadth:")
#convert into float type
L1=float(L)
B1=float(B)
#cal Area of Rect
ar=L1*B1
#display the result
print("\tLength of Rect={}".format(L1))
print("\tBreadth of Rect={}".format(B1))
print("\tArea of Rect={}".format(ar))