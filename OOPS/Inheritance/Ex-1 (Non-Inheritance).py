#Program Without Using Inheritance
class c1:
    def disp1(self):
        print("Display of c1")
class c2:
    def disp2(self):
        print("Display of c2")
class c3:
    def disp3(self):
        print("Display of c3")
#Main Program
o1=c1()  #Creating Object
o2=c2()
o3=c3()
o1.disp1()  #Displaying the Object
o2.disp2()
o3.disp3()